def refresh_costs(base_url: str) -> None:
    key = os.environ.get("LIFEASTRO_API_KEY", "")
    url = base_url.rstrip("/") + "/v1/meta/endpoints"
    req = urllib.request.Request(url, headers={"Accept": "application/json"})
    if key:
        req.add_header("Authorization", f"Bearer {key}")
    with urllib.request.urlopen(req, timeout=30) as resp:
        body = json.loads(resp.read())
    routes = {
        r["path"]: r["cost"]
        for r in body["routes"]
        if r.get("method", "GET") == "GET" and str(r["path"]).startswith("/v1/")
    }
    snapshot = {
        "source": f"GET {base_url.rstrip('/')}/v1/meta/endpoints",
        "fetched": _dt.date.today().isoformat(),
        "routes": dict(sorted(routes.items())),
    }
    COSTS.write_text(json.dumps(snapshot, indent=1, ensure_ascii=False) + "\n")
    print(f"Wrote {COSTS.relative_to(ROOT)}: {len(routes)} routes from {snapshot['source']}")


def _template_regex(path: str) -> re.Pattern[str]:
    parts = re.split(r"\{[^}]+\}", path)
    return re.compile("^" + "[^/]+".join(re.escape(p) for p in parts) + "$")


def cost_lookup() -> dict[str, int]:
    if not COSTS.exists():
        return {}
    routes: dict[str, int] = json.loads(COSTS.read_text())["routes"]
    return routes


def cost_for(path: str, routes: dict[str, int]) -> int | None:
    if path in routes:
        return routes[path]
    norm = re.sub(r"\{[^}]+\}", "{}", path)
    # Same template with other placeholder names, or a literal path (D9) of a template.
    matches = [
        (route.count("{"), cost)
        for route, cost in routes.items()
        if re.sub(r"\{[^}]+\}", "{}", route) == norm or _template_regex(route).match(path)
    ]
    return min(matches)[1] if matches else None


