TYPE_IMPORTS = ("Ayanamsa", "BirthInput", "HouseSystem", "Locale", "NatalWindowBirth")


def doc_escape(text: str) -> str:
    return re.sub(r"\s+", " ", text).strip().replace("\\", "\\\\").replace('"""', '\\"\\"\\"')


def wrap(text: str, indent: str, width: int = 100) -> list[str]:
    return [
        indent + line
        for line in textwrap.wrap(
            text, width - len(indent), break_long_words=False, break_on_hyphens=False
        )
    ]


def doc_block(text: str, indent: str) -> list[str]:
    """A docstring for one paragraph of text."""
    lines = wrap(doc_escape(text), indent, 97)
    lines[0] = indent + '"""' + lines[0][len(indent) :]
    if len(lines) == 1:
        return [lines[0] + '"""']
    return [*lines, indent + '"""']


# camelCase names of the Node SDK (inputs, methods, groups) -> their Python names,
# so a description that says `onDate` or `kundliFacts` reads `on_date` / `kundli_facts`.
NODE_NAMES: dict[str, str] = {}
_CAMEL = re.compile(r"\b([a-z]+[A-Z][A-Za-z0-9]*)\b(?!\.[A-Za-z])")  # not a prefix: personA.date


def collect_node_names(methods: list[Method]) -> None:
    for m in methods:
        names = [m.entry["method"], *m.entry["ns"].split(".")]
        names += [p.node for p in m.params]
        for name in names:
            if _CAMEL.fullmatch(name):
                NODE_NAMES[name] = snake(name).rstrip("_")


def pythonize(text: str) -> str:
    return _CAMEL.sub(lambda mt: NODE_NAMES.get(mt.group(1), mt.group(1)), text)


def docstring(m: Method, indent: str) -> list[str]:
    desc = doc_escape(pythonize(m.entry["desc"] or m.entry["path"]))
    lines = wrap(desc, indent, 97)
    lines[0] = indent + '"""' + lines[0][len(indent) :]
    lines.append("")
    if m.cost is not None:
        lines.append(f"{indent}Cost: {m.cost} credit{'' if m.cost == 1 else 's'} per call.")
        lines.append("")
    renamed = []
    for p in m.params:
        if p.kind == "object":
            if p.prefixes[0].rstrip(".") != p.name:
                renamed.append(f"``{p.name}`` -> ``{p.prefixes[0]}*``")
            continue
        for w in p.wires:
            if w != p.name and not (p.name == "lang" and w == "locale"):
                renamed.append(f"``{p.name}`` -> ``{w}``")
    if renamed:
        lines.extend(wrap("Wire names: " + ", ".join(renamed) + ".", indent))
        lines.append("")
    lines.append(f"{indent}``GET {m.entry['path']}``")
    lines.append(f'{indent}"""')
    return lines


def signature(m: Method, is_async: bool, indent: str) -> list[str]:
    ordered = [p for p in m.params if p.required] + [p for p in m.params if not p.required]
    out = [
        f"{indent}{'async ' if is_async else ''}def {m.py_name}(",
        f"{indent}    self,",
        f"{indent}    *,",
    ]
    for p in ordered:
        if p.required:
            out.append(f"{indent}    {p.name}: {p.type},")
        else:
            out.append(f"{indent}    {p.name}: {p.type} | None = None,")
    out.append(f"{indent}    request_options: RequestOptions | None = None,")
    out.append(f"{indent}) -> Any:")
    return out


def body(m: Method, is_async: bool, indent: str) -> list[str]:
    out: list[str] = []
    path_params = [p for p in m.params if p.kind == "path"]
    if path_params:
        values = ", ".join(f'"{p.node}": {p.name}' for p in path_params)
        path_expr = f'build_path("{m.entry["path"]}", {{{values}}})'
    else:
        path_expr = f'"{m.entry["path"]}"'
    if not m.ops and not any(p.kind == "object" for p in m.params):
        call = f"self._c.request({path_expr}, {{}}, request_options=request_options)"
        out.append(f"{indent}return {'await ' if is_async else ''}{call}")
        return out
    out.append(f"{indent}_q: QueryParams = {{}}")
    # Object params first (their builders run before the extras in Node), then
    # every scalar put in manifest order: a later put of the same wire wins.
    for p in m.params:
        if p.kind != "object":
            continue
        out.append(f'{indent}put_fields(_q, {p.name}, "{p.prefixes[0]}")')
        if p.place_unprefixed:
            out.append(f'{indent}put_fields(_q, {p.name}, "", ("lat", "lon"))')
    for op in m.ops:
        out.append(f'{indent}put(_q, "{op.wire}", {op.expr})')
    call = f"self._c.request({path_expr}, _q, request_options=request_options)"
    out.append(f"{indent}return {'await ' if is_async else ''}{call}")
    return out


def method_src(m: Method, is_async: bool, indent: str = "    ") -> str:
    lines = signature(m, is_async, indent)
    lines += docstring(m, indent + "    ")
    lines += body(m, is_async, indent + "    ")
    return "\n".join(lines)


def class_src(
    name: str,
    doc: str,
    methods: list[Method],
    is_async: bool,
    children: list[tuple[str, str]] | None = None,
) -> str:
    core = "AsyncCore" if is_async else "SyncCore"
    lines = [f"class {name}:", *doc_block(doc, "    "), ""]
    if children:
        for attr, cls in children:
            lines.append(f"    {attr}: {cls}")
        lines.append("")
    lines.append(f"    def __init__(self, client: {core}) -> None:")
    lines.append("        self._c = client")
    for attr, cls in children or []:
        lines.append(f"        self.{attr} = {cls}(client)")
    for m in methods:
        lines.append("")
        lines.append(method_src(m, is_async))
    return "\n".join(lines)


def module_imports(methods: list[Method]) -> str:
    helpers: set[str] = set()
    types = {"QueryParams", "RequestOptions"}
    for m in methods:
        for p in m.params:
            for t in TYPE_IMPORTS:
                if re.search(rf"\b{t}\b", p.type):
                    types.add(t)
            if p.kind == "path":
                helpers.add("build_path")
            if p.kind == "object":
                helpers.add("put_fields")
        if m.ops:
            helpers.add("put")
        if any("today_in(" in op.expr for op in m.ops):
            helpers.add("today_in")
    uses_q = any(m.ops or any(p.kind == "object" for p in m.params) for m in methods)
    if not uses_q:
        types.discard("QueryParams")
    lines = [
        "from __future__ import annotations",
        "",
        "from typing import Any",
        "",
        "from .._core import AsyncCore, SyncCore",
    ]
    if helpers:
        lines.append(f"from .._params import {', '.join(sorted(helpers))}")
    lines.append(f"from ..types import {', '.join(sorted(types))}")
    return "\n".join(lines)


def write_flat(ns: str, methods: list[Method]) -> tuple[str, str, str]:
    cls = pascal(ns)
    doc = NS_DOC.get(ns, ns)
    src = "\n".join(
        [
            HEADER + "\n".join(doc_block(doc, "")),
            "",
            module_imports(methods),
            "",
            "",
            class_src(cls, doc + f" Use ``client.{snake(ns)}``.", methods, False),
            "",
            "",
            class_src(
                "Async" + cls,
                doc + f" Use ``client.{snake(ns)}`` on :class:`AsyncLifeAstro`.",
                methods,
                True,
            ),
            "",
        ]
    )
    module = snake(ns)
    (OUT / f"{module}.py").write_text(src)
    return module, cls, snake(ns)


def write_western(by_ns: dict[str, list[Method]]) -> tuple[str, str, str]:
    direct = by_ns.get("western", [])
    child_ns = sorted(ns for ns in by_ns if ns.startswith("western."))
    all_methods = direct + [m for ns in child_ns for m in by_ns[ns]]
    parts = [
        HEADER + "\n".join(doc_block(NS_DOC["western"], "")),
        "",
        module_imports(all_methods),
        "",
        "",
    ]
    children = []
    for ns in child_ns:
        sub = ns.split(".")[1]
        cls = "Western" + pascal(sub)
        children.append((snake(sub), cls))
        doc = f"Western ``{snake(sub)}`` endpoints: ``client.western.{snake(sub)}``."
        parts += [class_src(cls, doc, by_ns[ns], False), "", ""]
        parts += [class_src("Async" + cls, doc, by_ns[ns], True), "", ""]
    parts.append(class_src("Western", NS_DOC["western"], direct, False, children))
    parts += ["", ""]
    parts.append(
        class_src(
            "AsyncWestern", NS_DOC["western"], direct, True, [(a, "Async" + c) for a, c in children]
        )
    )
    parts.append("")
    (OUT / "western.py").write_text("\n".join(parts))
    return "western", "Western", "western"


def write_index(written: list[tuple[str, str, str]]) -> None:
    written = sorted(written, key=lambda w: w[2])
    lines = [HEADER + '"""Every resource group of the API, as attributes of the client."""', ""]
    lines.append("from __future__ import annotations")
    lines.append("")
    lines.append("from .._core import AsyncCore, SyncCore")
    for module, cls, _ in written:
        lines.append(f"from .{module} import Async{cls}, {cls}")
    lines += ["", "", "class Resources:"]
    lines.append(
        '    """The resource groups of :class:`LifeAstro`: ``client.panchang`` and so on."""'
    )
    lines.append("")
    for _, cls, attr in written:
        lines.append(f"    {attr}: {cls}")
    lines.append("")
    lines.append("    def __init__(self, client: SyncCore) -> None:")
    for _, cls, attr in written:
        lines.append(f"        self.{attr} = {cls}(client)")
    lines += ["", "", "class AsyncResources:"]
    lines.append('    """The resource groups of :class:`AsyncLifeAstro`."""')
    lines.append("")
    for _, cls, attr in written:
        lines.append(f"    {attr}: Async{cls}")
    lines.append("")
    lines.append("    def __init__(self, client: AsyncCore) -> None:")
    for _, cls, attr in written:
        lines.append(f"        self.{attr} = Async{cls}(client)")
    names = sorted(
        ["Resources", "AsyncResources"]
        + [c for _, c, _ in written]
        + ["Async" + c for _, c, _ in written]
    )
    lines += ["", "", "__all__ = ["]
    lines += [f'    "{n}",' for n in names]
    lines.append("]")
    lines.append("")
    (OUT / "__init__.py").write_text("\n".join(lines))


def write_manifest(methods: list[Method]) -> None:
    out = []
    for m in sorted(methods, key=lambda m: m.key):
        out.append(
            {
                "key": m.key,
                "py": f"{m.py_ns}.{m.py_name}",
                "path": m.entry["path"],
                "shape": m.entry["shape"],
                "cost": m.cost,
                "pathParams": m.entry["pathParams"],
                "extras": m.entry["extras"],
                "params": [
                    {
                        "name": p.name,
                        "node": p.node,
                        "type": p.type,
                        "required": p.required,
                        "kind": p.kind,
                        **(
                            {"prefix": p.prefixes[0], "place": p.place_unprefixed}
                            if p.kind == "object"
                            else {"wires": p.wires}
                        ),
                    }
                    for p in m.params
                ],
            }
        )
    MANIFEST_OUT.write_text(json.dumps(out, indent=1, ensure_ascii=False) + "\n")


def write_fixture() -> None:
    if not EXAMPLES.exists():
        print(f"examples.json not found at {EXAMPLES}; {FIXTURE_OUT.relative_to(ROOT)} left as is.")
        return
    ex = json.loads(EXAMPLES.read_text())
    out = {
        path: {
            "status": v.get("status"),
            "required": v.get("required") or [],
            "params": v.get("params") or {},
        }
        for path, v in sorted(ex.items())
    }
    FIXTURE_OUT.parent.mkdir(parents=True, exist_ok=True)
    FIXTURE_OUT.write_text(json.dumps(out, indent=1, ensure_ascii=False) + "\n")


def format_sources() -> None:
    ruff = [sys.executable, "-m", "ruff"]
    try:
        subprocess.run([*ruff, "check", "--quiet", "--fix", "--select", "I", str(OUT)], check=True)
        subprocess.run([*ruff, "format", "--quiet", str(OUT)], check=True)
    except (subprocess.CalledProcessError, FileNotFoundError):
        print("`ruff` failed or is not installed in this Python; run `ruff format` by hand.")


def main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--costs-url", help="refresh scripts/costs.json from GET <url>/v1/meta/endpoints first"
    )
    args = parser.parse_args()
    if args.costs_url:
        refresh_costs(args.costs_url)

    entries = load_entries()
    costs = cost_lookup()
    methods = [resolve(e, costs) for e in entries]
    collect_node_names(methods)

    seen: dict[str, str] = {}
    for m in methods:
        key = f"{m.py_ns}.{m.py_name}"
        if key in seen:
            raise SystemExit(
                f"Python method collision: {key} from {seen[key]} and {m.entry['path']}"
            )
        seen[key] = m.entry["path"]
        if m.cost is None:
            print(f"warning: no credit cost for {m.entry['path']} in {COSTS.name}")
        said = re.search(r"\((\d[\d,]*) credits?\)", m.entry["desc"])
        if said and m.cost is not None and int(said.group(1).replace(",", "")) != m.cost:
            print(
                f"warning: {m.key} description says {said.group(1)} credits, "
                f"{COSTS.name} says {m.cost}"
            )

    by_ns: dict[str, list[Method]] = {}
    for m in methods:
        by_ns.setdefault(m.entry["ns"], []).append(m)
    for group in by_ns.values():
        group.sort(key=lambda m: m.py_name)

    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)
    written = [write_flat(ns, by_ns[ns]) for ns in sorted(by_ns) if not ns.startswith("western")]
    written.append(write_western(by_ns))
    write_index(written)
    write_manifest(methods)
    write_fixture()
    format_sources()

    groups = ", ".join(sorted(w[2] for w in written))
    print(
        f"Generated {len(written) + 1} files in src/lifeastroapi/resources, "
        f"{len(methods)} methods ({len(entries)} endpoints)."
    )
    print(f"Groups: {groups}")


if __name__ == "__main__":
    main()
