@dataclass
class Param:
    name: str  # Python keyword argument
    node: str  # Node SDK input field
    type: str  # Python annotation
    required: bool
    kind: str  # "path" | "scalar" | "object"
    wires: list[str] = field(default_factory=list)  # scalar: wire names
    prefixes: list[str] = field(default_factory=list)  # object: "boy." -> boy.date, ...
    place_unprefixed: bool = False  # object: also send lat/lon unprefixed


@dataclass
class Op:
    param: str
    wire: str
    expr: str  # Python expression of the value


def snake(name: str) -> str:
    s = re.sub(r"(?<=[a-z0-9])([A-Z])", r"_\1", name)
    s = re.sub(r"(?<=[A-Z])([A-Z][a-z])", r"_\1", s)
    s = re.sub(r"[^A-Za-z0-9_]", "_", s).lower()
    return s + "_" if keyword.iskeyword(s) else s


def pascal(name: str) -> str:
    return "".join(w[:1].upper() + w[1:] for w in re.split(r"[^A-Za-z0-9]+", name) if w)


def scalar(node: str, type_: str, required: bool, wire: str | None = None) -> Param:
    return Param(snake(node), node, type_, required, "scalar", [wire or node])


def obj(node: str, type_: str, required: bool, prefix: str, place: bool = False) -> Param:
    return Param(
        snake(node), node, type_, required, "object", prefixes=[prefix], place_unprefixed=place
    )


def ayanamsa() -> Param:
    return scalar("ayanamsa", "Ayanamsa", False)


def house() -> Param:
    return scalar("houseSystem", "HouseSystem", False, "house_system")


