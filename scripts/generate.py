_DUMP_JS = """
import { pathToFileURL } from "node:url";
const m = await import(pathToFileURL(process.argv[1]).href);
const out = m.entries.map((e) => ({
  path: e.path,
  shape: e.shape,
  desc: e.desc ?? "",
  ns: e._resolved.ns,
  method: e._resolved.method,
  pathParams: e.pathParams ?? [],
  extras: (e.extras ?? []).map((x) => ({
    wire: x.wire, type: x.type, required: !!x.required, field: x.name ?? m.camel(x.wire),
  })),
}));
process.stdout.write(JSON.stringify(out));
"""


def load_entries() -> list[dict[str, Any]]:
    manifest = NODE_SDK / "scripts" / "manifest.mjs"
    if not manifest.exists():
        sys.exit(f"Node SDK manifest not found at {manifest}. Set LIFEASTRO_NODE_SDK.")
    node = shutil.which("node")
    if node is None:
        sys.exit("`node` is needed to read scripts/manifest.mjs of the Node SDK.")
    raw = subprocess.check_output(
        [node, "--input-type=module", "-e", _DUMP_JS, str(manifest)], cwd=NODE_SDK
    )
    entries: list[dict[str, Any]] = json.loads(raw)
    return entries


