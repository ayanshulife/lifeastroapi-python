def extra_type(x: dict[str, Any], node: str) -> str:
    if node in ("lang", "locale") or x["type"] == "locale":
        return "Locale"
    if node == "ayanamsa":
        return "Ayanamsa"
    if node == "houseSystem":
        return "HouseSystem"
    return {"number": "float", "integer": "int", "boolean": "bool"}.get(x["type"], "str")


def base_expr(shape: str, p: Param) -> str:
    """Value expression of a base-shape scalar (defaults as in src/params.ts)."""
    if shape == "moment" and p.node == "date":
        return "date if date is not None else today_in(tz)"
    if shape == "instant" and p.node == "tz":
        return '"UTC" if tz is None else tz'
    if shape == "instant" and p.node == "date":
        return 'date if date is not None else today_in("UTC" if tz is None else tz)'
    if shape == "rashi" and p.node == "rashi":
        return "rashi.strip().lower()"
    return p.name


@dataclass
class Method:
    entry: dict[str, Any]
    params: list[Param]
    ops: list[Op]
    cost: int | None

    @property
    def py_ns(self) -> str:
        return ".".join(snake(part) for part in self.entry["ns"].split("."))

    @property
    def py_name(self) -> str:
        return snake(self.entry["method"])

    @property
    def key(self) -> str:
        return f"{self.entry['ns']}.{self.entry['method']}"


def resolve(entry: dict[str, Any], costs: dict[str, int]) -> Method:
    shape = entry["shape"]
    if shape not in SHAPES:
        raise SystemExit(f"Unknown shape {shape!r} for {entry['path']}")
    params: list[Param] = []
    ops: list[Op] = []
    by_name: dict[str, Param] = {}

    def add(p: Param) -> Param:
        if p.name in RESERVED:
            raise SystemExit(f"{entry['path']}: parameter {p.name!r} collides with a reserved name")
        existing = by_name.get(p.name)
        if existing is None:
            params.append(p)
            by_name[p.name] = p
            return p
        if existing.kind == "object" or p.kind == "object":
            raise SystemExit(f"{entry['path']}: {p.name!r} is both a scalar and an object")
        existing.required = existing.required or p.required
        return existing

    for n in entry["pathParams"]:
        add(Param(snake(n), n, "int | str" if n in ("n", "number") else "str", True, "path"))

    for p in SHAPES[shape]():
        target = add(p)
        if p.kind == "object":
            continue
        for w in p.wires:
            ops.append(Op(target.name, w, base_expr(shape, p)))

    for x in entry["extras"]:
        node = x["field"]
        p = scalar(node, extra_type(x, node), x["required"], x["wire"])
        target = add(p)  # a path or base parameter of the same name is reused
        wires = [x["wire"], "locale"] if x["wire"] == "lang" else [x["wire"]]
        for w in wires:
            ops.append(Op(target.name, w, target.name))
            if w not in target.wires:
                target.wires.append(w)

    return Method(entry, params, ops, cost_for(entry["path"], costs))


