"""Code generator for the Python SDK.

Reads the endpoint manifest of the Node SDK (``scripts/endpoints_part1.json`` +
``endpoints_part2.json``, resolved by ``scripts/manifest.mjs``: per-path
overrides, the ``lang`` rules and the namespace / method names) and writes:

    src/lifeastroapi/resources/*.py   one module per group, sync + async class
    scripts/manifest.json             the resolved manifest with the Python parameters
    tests/fixtures/examples.json      request params of every endpoint (from the
                                      website's examples.json, when it is found)

The manifest is read through ``manifest.mjs`` (with ``node``) rather than by
copying its rules, so the Node, Dart and Python SDKs always agree on the
endpoint list, method names and which methods take ``lang``.

Credit costs for the docstrings come from ``scripts/costs.json``, a snapshot of
``GET /v1/meta/endpoints``. Refresh it with ``--costs-url``.

    python scripts/generate.py
    python scripts/generate.py --costs-url http://127.0.0.1:18080   # key from LIFEASTRO_API_KEY

Environment:
    LIFEASTRO_NODE_SDK   path to the Node SDK repo (default ../lifeastroapi-node)
    LIFEASTRO_EXAMPLES   path to the website's examples.json (default
                         ../LifeAstroAPI/LifeAstroApiWebsite/lib/generated/examples.json)
"""

